import path from "node:path";
import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";

/**
 * Performance-build config (ticket 13) — test scaffolding, NOT a product
 * config. It exists so `tools/src/perf-check.ts` can build the leaderboard
 * against the SYNTHETIC 220-Model fixture (user story 54: "the leaderboard
 * stays responsive with 200+ Models loaded") without a single synthetic row
 * ever entering packages/data, which keeps real Published Results
 * exclusively.
 *
 * How it is used (only by the perf check, never by a real deploy):
 *
 *   LLM_BENCH_DATA_DIR=/tmp/llm-bench-perf-… pnpm --filter web exec \
 *       vite build --config vite.perf.config.ts
 *
 * The directory in LLM_BENCH_DATA_DIR is generated by
 * tools/src/lib/perf-fixture.ts into a TEMP directory: models.json +
 * scores.json (synthetic), benchmarks.json / evaluation-settings.json /
 * pricing-config.json (byte-identical real catalogue), and an index.ts
 * module shim. This config aliases @llm-bench/data at that shim, so the
 * app, @llm-bench/scoring and the schema stay the real, shipped code —
 * only the data volume is synthetic.
 *
 * The output goes to <LLM_BENCH_DATA_DIR>/dist (emptyOutDir is explicit
 * because the directory is outside this root) and NEVER to apps/web/dist,
 * which stays the real-data build the rest of the test suite asserts
 * against.
 *
 * Like tools/src/lib/spa-static-server.ts, this file is deliberately not
 * part of apps/web's tsconfig include (apps/web has no @types/node for
 * process/path); it is linted like every other source file but type
 * checking belongs to the real build.
 */

const fixtureDataDir = process.env["LLM_BENCH_DATA_DIR"];
if (typeof fixtureDataDir !== "string" || fixtureDataDir === "") {
  throw new Error(
    "vite.perf.config.ts is the ticket-13 performance-build config: it needs " +
      "LLM_BENCH_DATA_DIR pointing at a directory generated by " +
      "tools/src/lib/perf-fixture.ts. For a real build use vite.config.ts " +
      "(pnpm build) instead.",
  );
}

export default defineConfig({
  plugins: [react()],
  // Same routing contract as the real config (ADR-0003).
  appType: "spa",
  resolve: {
    alias: {
      "@llm-bench/data": path.resolve(fixtureDataDir, "index.ts"),
    },
  },
  build: {
    outDir: path.resolve(fixtureDataDir, "dist"),
    emptyOutDir: true,
  },
});
